"""PyHealth MLP adapter for SHHS multimodal 30-second sleep-stage epochs.

This is an epoch-level baseline, not the CNN/Transformer/temporal wav2sleep
architecture. It accepts batches generated by SHHSMultimodalSleepStaging and
collate_shhs_epochs, with the input_mask set by Person 1's masking utilities.

Expected batch: ecg [B,1024], abd/thx [B,256], availability_mask and
input_mask [B,3] (ECG, ABD, THX), label [B] in {0,1,2,3}.

The 1539-feature fusion input concatenates masked signals and the three mask
bits. The small schema fixture configures PyHealth's existing MLP; it is never
used as training data.
"""

from __future__ import annotations

import torch
from torch import Tensor, nn

from pyhealth.datasets import create_sample_dataset
from pyhealth.models import MLP

MODALITIES = ("ecg", "abd", "thx")
SIGNAL_LENGTHS = {"ecg": 1024, "abd": 256, "thx": 256}
CLASS_NAMES = ("Wake", "Light", "Deep", "REM")


class PyHealthMaskedMLP(nn.Module):
    """Adapt a masked multimodal SHHS epoch batch to the existing PyHealth MLP."""

    def __init__(self, hidden_dim: int = 64) -> None:
        super().__init__()
        input_dim = sum(SIGNAL_LENGTHS.values()) + len(MODALITIES)
        schema_samples = [
            {
                "patient_id": f"schema-patient-{label}",
                "visit_id": f"schema-visit-{label}",
                "fusion_input": [0.0] * input_dim,
                "label": label,
            }
            for label in range(len(CLASS_NAMES))
        ]
        self.schema_dataset = create_sample_dataset(
            samples=schema_samples,
            input_schema={"fusion_input": "tensor"},
            output_schema={"label": "multiclass"},
            dataset_name="shhs_multimodal_schema_fixture",
            in_memory=True,
        )
        self.core = MLP(
            dataset=self.schema_dataset,
            embedding_dim=hidden_dim,
            hidden_dim=hidden_dim,
            n_layers=2,
        )

    def forward(self, batch: dict[str, Tensor]) -> dict[str, Tensor]:
        available = batch["availability_mask"].bool()
        selected = batch["input_mask"].bool()
        labels = batch["label"].long()

        if available.ndim != 2 or available.shape[1] != len(MODALITIES):
            raise ValueError("availability_mask must be [B,3]")
        if selected.shape != available.shape:
            raise ValueError("input_mask must be [B,3]")
        if (selected & ~available).any():
            raise ValueError("input_mask selected an unavailable modality")
        if not bool(selected.any(dim=1).all()):
            raise ValueError("Each example must retain at least one modality")
        if labels.shape != (available.shape[0],):
            raise ValueError("label must be [B]")
        if not bool(((0 <= labels) & (labels < len(CLASS_NAMES))).all()):
            raise ValueError("Labels must be in {0,1,2,3}; exclude unscored epochs")

        parts = []
        for index, name in enumerate(MODALITIES):
            signal = batch[name].float()
            expected = (available.shape[0], SIGNAL_LENGTHS[name])
            if tuple(signal.shape) != expected:
                raise ValueError(f"{name} must be {expected}, got {tuple(signal.shape)}")
            parts.append(signal * selected[:, index : index + 1].to(signal.dtype))
        parts.append(selected.to(dtype=torch.float32))
        fused = torch.cat(parts, dim=1)  # [B,1539]
        return self.core(fusion_input=fused, label=labels)
